// Write src/agent/lookAlikes.ts: the letters that look like Latin ones, from Unicode's confusables
// data (UTS #39, https://www.unicode.org/Public/security/latest/confusables.txt), for telling an
// agent's text that would pass for the app's name (readsAs in src/agent/protocol.ts).
//
//   node scripts/look-alikes.mjs <path to confusables.txt>
//
// Kept: every single character whose prototype is Latin letters or digits once its accents and
// other marks are dropped (Lisu ꓝ as F, Greek Ϝ as F, Canadian ᖴ as F, Cherokee Ꮮ as L...).
// The table is small and changes only with a new Unicode version, so it's kept in the repository.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'agent', 'lookAlikes.ts');
const file = process.argv[2];
if (!file) {
  console.error('Give the path to confusables.txt (https://www.unicode.org/Public/security/latest/confusables.txt).');
  process.exit(1);
}
const text = readFileSync(file, 'utf8');
const version = /^# Version: (\S+)/m.exec(text)?.[1] ?? 'unknown';
const chars = (hex) => hex.trim().split(/\s+/).map((h) => String.fromCodePoint(parseInt(h, 16))).join('');
const map = new Map();
for (const line of text.split('\n')) {
  const data = line.split('#')[0].trim();
  if (!data) continue;
  const [from, to] = data.split(';');
  const source = chars(from);
  if ([...source].length !== 1 || /^[a-z]$/.test(source)) continue;
  const target = chars(to).normalize('NFD').replace(/\p{M}/gu, '');
  if (!/^[A-Za-z0-9]+$/.test(target)) continue;
  map.set(source, target.toLowerCase());
}
const entries = [...map].sort(([a], [b]) => a.codePointAt(0) - b.codePointAt(0));
// One string: each character, then what it reads as, then a space
const table = entries.map(([s, t]) => `${s}${t}`).join(' ');
const escaped = [...table].map((c) => (c.codePointAt(0) < 0x20 || c.codePointAt(0) > 0x7e || c === '\\' || c === "'" ? `\\u{${c.codePointAt(0).toString(16)}}` : c)).join('');
writeFileSync(
  OUT,
  `/**
 * Letters that look like Latin ones, as those letters: Unicode's confusables data (UTS #39,
 * version ${version}), cut to the characters whose prototype is Latin letters or digits once its
 * marks are dropped (${entries.length} of them). For telling text that would pass for the app's
 * name (readsAs in protocol.ts). Generated by scripts/look-alikes.mjs from confusables.txt: edit
 * that, not this. The data is © Unicode, Inc., under the Unicode License v3
 * (https://www.unicode.org/license.txt).
 */

const TABLE = '${escaped}';

/** Each look-alike character and the Latin letters (or digits) it reads as, lower case. */
export const LOOK_ALIKE_LETTERS: ReadonlyMap<string, string> = new Map(
  TABLE.split(' ').map((entry) => {
    const [first, ...rest] = [...entry];
    return [first, rest.join('')] as [string, string];
  })
);
`
);
console.log(`Wrote ${OUT}: ${entries.length} characters (Unicode ${version}).`);
