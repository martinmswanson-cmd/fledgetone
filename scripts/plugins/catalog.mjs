// Write the built-in plugin catalogs from the compiled families in public/bos-beat-box-plugins/
// (each family's plugins as its WebAssembly describes them): src/audio/plugins/pluginCatalog.ts
// for the permissively licensed families, pluginCatalogGpl.ts for the GPL ones (only builds with
// VITE_GPL_PLUGINS=1 include it). Run after building a family: node scripts/plugins/catalog.mjs
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const pluginsDir = join(root, 'public/bos-beat-box-plugins');
const families = JSON.parse(readFileSync(join(root, 'scripts/plugins/families.json'), 'utf8'));

/** Every file under `dir` ending in `ext`, as "sub/folder/name" (no extension), sorted. */
function listFiles(dir, ext) {
  const out = [];
  const walk = (d) => {
    for (const f of readdirSync(d).sort((a, b) => a.localeCompare(b))) {
      const p = join(d, f);
      if (statSync(p).isDirectory()) walk(p);
      else if (f.endsWith(ext)) out.push(relative(dir, p).slice(0, -ext.length).split('\\').join('/'));
    }
  };
  walk(dir);
  return out;
}

const plain = [];
const gpl = [];
for (const f of families) {
  const fileName = f.file ?? `${f.family}.wasm`;
  const file = join(pluginsDir, fileName);
  if (!existsSync(file)) {
    console.warn(`skipping ${f.family}: ${file} not built`);
    continue;
  }
  const bytes = readFileSync(file);
  const mod = await WebAssembly.compile(bytes);
  const imports = {};
  for (const i of WebAssembly.Module.imports(mod)) (imports[i.module] ??= {})[i.name] = () => 0;
  const { exports: e } = await WebAssembly.instantiate(mod, imports);
  e._initialize?.();
  const str = (p) => {
    const m = new Uint8Array(e.memory.buffer);
    let end = p;
    while (m[end]) end++;
    return Buffer.from(m.subarray(p, end)).toString('utf8');
  };
  const plugins = [];
  for (let i = 0; i < e.bb_count(); i++) {
    const info = JSON.parse(str(e.bb_info(i)));
    const presets = f.presets?.[info.name];
    plugins.push({
      name: info.name,
      category: info.category,
      about: info.about,
      ...(info.instrument ? { instrument: true } : {}),
      ...(info.tags?.length ? { tags: info.tags } : {}),
      ...(presets ? { presetFiles: { dir: presets.dir, ext: presets.ext, names: listFiles(join(pluginsDir, presets.dir), presets.ext) } } : {}),
    });
  }
  (f.gpl ? gpl : plain).push({ family: f.family, label: f.label, licence: f.licence, gpl: !!f.gpl, file: fileName, bytes: bytes.length, hash: createHash('sha1').update(bytes).digest('hex').slice(0, 12), plugins });
  console.log(`${f.family}: ${plugins.length} plugins, ${(bytes.length / 1e6).toFixed(1)} MB${f.gpl ? ' (GPL)' : ''}`);
}
const header = `/** The built-in plugins, by family (generated by scripts/plugins/catalog.mjs from the compiled families: don't edit). */\nimport type { PluginFamily } from './pluginTypes';\n\n`;
writeFileSync(
  join(root, 'src/audio/plugins/pluginCatalog.ts'),
  header +
    `export const PLUGIN_FAMILIES: PluginFamily[] = ${JSON.stringify(plain, null, 1)};\n\n` +
    `/** The GPL families (in pluginCatalogGpl.ts, only in builds with VITE_GPL_PLUGINS=1), by name, to explain why one is missing */\n` +
    `export const GPL_FAMILY_NAMES: string[] = ${JSON.stringify(gpl.map((f) => f.family))};\n`
);
writeFileSync(join(root, 'src/audio/plugins/pluginCatalogGpl.ts'), header + `export const GPL_PLUGIN_FAMILIES: PluginFamily[] = ${JSON.stringify(gpl, null, 1)};\n`);
