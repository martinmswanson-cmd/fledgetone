// Write src/audio/plugins/pluginCatalog.ts from the compiled plugin families in
// public/bos-beat-box-plugins/ (each family's plugins as its WebAssembly describes them).
// Run after building a family: node scripts/plugins/catalog.mjs
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const families = JSON.parse(readFileSync(join(root, 'scripts/plugins/families.json'), 'utf8'));
const out = [];
for (const f of families) {
  const file = join(root, 'public/bos-beat-box-plugins', `${f.family}.wasm`);
  if (!existsSync(file)) {
    console.warn(`skipping ${f.family}: ${file} not built`);
    continue;
  }
  const bytes = readFileSync(file);
  const mod = await WebAssembly.compile(bytes);
  const imports = {};
  for (const i of WebAssembly.Module.imports(mod)) (imports[i.module] ??= {})[i.name] = () => 0;
  const { exports: e } = await WebAssembly.instantiate(mod, imports);
  e._initialize?.();
  const str = (p) => {
    const m = new Uint8Array(e.memory.buffer);
    let end = p;
    while (m[end]) end++;
    return Buffer.from(m.subarray(p, end)).toString('utf8');
  };
  const plugins = [];
  for (let i = 0; i < e.bb_count(); i++) {
    const info = JSON.parse(str(e.bb_info(i)));
    plugins.push({ name: info.name, category: info.category, about: info.about, ...(info.instrument ? { instrument: true } : {}), ...(info.tags?.length ? { tags: info.tags } : {}) });
  }
  out.push({ family: f.family, label: f.label, licence: f.licence, gpl: !!f.gpl, file: `${f.family}.wasm`, bytes: bytes.length, hash: createHash('sha1').update(bytes).digest('hex').slice(0, 12), plugins });
  console.log(`${f.family}: ${plugins.length} plugins, ${(bytes.length / 1e6).toFixed(1)} MB`);
}
writeFileSync(
  join(root, 'src/audio/plugins/pluginCatalog.ts'),
  `/** The built-in plugins, by family (generated by scripts/plugins/catalog.mjs from the compiled families: don't edit). */\n` +
    `import type { PluginFamily } from './pluginTypes';\n\n` +
    `export const PLUGIN_FAMILIES: PluginFamily[] = ${JSON.stringify(out, null, 1)};\n`
);
