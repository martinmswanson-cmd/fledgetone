#!/usr/bin/env python3
"""Build the Faust family: build.py <out.wasm> [object dir]

Compiles every program in plugins.json with the Faust compiler (2.70, with its own libraries:
apt's faust package) to C++ in gen/, then to WebAssembly with emsdk's em++ (on the PATH).
"""
import json, os, subprocess, sys, hashlib
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1]
OBJ = sys.argv[2] if len(sys.argv) > 2 else '/tmp/bb-faust-obj'
GEN = os.path.join(HERE, 'gen')
os.makedirs(GEN, exist_ok=True); os.makedirs(OBJ, exist_ok=True)
plugins = json.load(open(os.path.join(HERE, 'plugins.json')))
trims = json.load(open(os.path.join(HERE, 'trims.json'))) if os.path.exists(os.path.join(HERE, 'trims.json')) else {}
ok = []
for p in plugins:
    pid = p['id']
    src = p['file'] if p.get('file') else os.path.join(GEN, pid + '.dsp')
    if not p.get('file'):
        open(src, 'w').write(p['code'] + '\n')
    cpp = os.path.join(GEN, pid + '.cpp')
    inc = ['-I', os.path.dirname(src)]
    r = subprocess.run(['faust', '-lang', 'cpp', '-cn', 'Faust_' + pid, '-scn', 'FaustDSP', '-a', os.path.join(HERE, 'arch.cpp'), '-i', *inc, src, '-o', cpp], capture_output=True, text=True)
    if r.returncode:
        print('faust failed:', pid, r.stderr.strip()[:300]); continue
    o = os.path.join(OBJ, pid + '.o')
    r = subprocess.run(['em++', '-O2', '-fno-exceptions', '-w', '-ffast-math', '-I', HERE, '-I', os.path.dirname(src), '-include', 'faustbase.h', '-c', cpp, '-o', o], capture_output=True, text=True)
    if r.returncode:
        print('compile failed:', pid, r.stderr.strip().splitlines()[:3]); continue
    ok.append(p)
reg = ['// Generated by build.py: the compiled programs']
for p in ok:
    reg.append(f'FaustDSP *new_{p["id"]}();')
reg.append('')
for p in ok:
    defaults = ';'.join(f'{k}={v}' for k, v in p.get('defaults', {}).items())
    reg.append(f'static const FaustDef faust_{p["id"]} = {{new_{p["id"]}, {trims.get(p["id"], 1.0)}f, "{defaults}"}};')
reg.append('#define BB_FAUST_FACTORIES \\')
reg += [f'    BB_FAUST_FACTORY({p["id"]}, {p["instrument"]}) \\' for p in ok]
reg.append('')
esc = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')
reg.append('#define BB_FAUST_DEFS \\')
reg += [f'    {{"{esc(p["name"])}", "{esc(p["category"])}", "{esc(p["about"])}", {p["instrument"]}, make_{p["id"]}}}, \\' for p in ok]
reg.append('')
open(os.path.join(GEN, 'registry.h'), 'w').write('\n'.join(reg) + '\n')
# Each program's factory, beside its class
for p in ok:
    # (In a namespace of its own: some programs' helper headers define the same functions)
    open(os.path.join(GEN, p['id'] + '_new.cpp'), 'w').write(f'namespace ns_{p["id"]} {{\n#include "{p["id"]}.cpp"\n}}\nFaustDSP *new_{p["id"]}() {{ return new ns_{p["id"]}::Faust_{p["id"]}(); }}\n')
objs = []
for p in ok:
    o = os.path.join(OBJ, p['id'] + '_new.o')
    subprocess.run(['em++', '-O2', '-fno-exceptions', '-w', '-ffast-math', '-I', HERE, '-I', GEN, '-I', os.path.dirname(p['file']) if p.get('file') else GEN, '-include', 'faustbase.h', '-c', os.path.join(GEN, p['id'] + '_new.cpp'), '-o', o], check=True)
    objs.append(o)
for f, o in [('bb_faust.cpp', 'bb.o'), ('../bbplug_impl.cpp', 'impl.o')]:
    subprocess.run(['em++', '-O2', '-fno-exceptions', '-I', HERE, '-I', os.path.join(HERE, '..'), '-c', os.path.join(HERE, f), '-o', os.path.join(OBJ, o)], check=True)
    objs.append(os.path.join(OBJ, o))
subprocess.run(['sh', os.path.join(HERE, '..', 'link.sh'), OUT, *objs], check=True)
print(len(ok), 'of', len(plugins), 'programs')
