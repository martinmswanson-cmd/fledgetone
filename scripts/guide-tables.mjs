// The guide's instrument list and the Credits tables (recordings and plugins),
// generated from the instrument catalog and src/credits.ts so they can't go stale. `npm run guide-tables` rewrites them in GUIDE.md;
// scripts/guideTables.test.mjs fails if they're out of date.
import { register } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

register(
  'data:text/javascript,' +
    encodeURIComponent(`export async function resolve(specifier, context, next) {
  try {
    return await next(specifier, context);
  } catch (err) {
    if (/^\\.\\.?\\//.test(specifier) && !/\\.[cm]?[jt]s$/.test(specifier)) return next(specifier + '.ts', context);
    throw err;
  }
}`)
);
const { INSTRUMENTS, CATEGORIES } = await import('../src/audio/instrumentCatalog.ts');
const { SAMPLE_CREDITS, PLUGIN_CREDITS, creditFor } = await import('../src/credits.ts');
const { PLUGIN_FAMILIES } = await import('../src/audio/plugins/pluginCatalog.ts');

export const GUIDE = fileURLToPath(new URL('../GUIDE.md', import.meta.url));
const playable = () => Object.values(INSTRUMENTS).filter((d) => d.kind !== 'slicer' && d.kind !== 'audio' && d.kind !== 'bus' && d.kind !== 'plugin' && d.kind !== 'return');
const recorded = (d) => !!d.samples;

/** Instruments whose samples come from no listed source. */
// The first recording's whole path: an ensemble's baseUrl is the samples folder, its recordings in each set's folder
const sourceOf = (d) => d.samples.baseUrl + Object.values(d.samples.samples)[0];
export const uncredited = () => playable().filter((d) => recorded(d) && !creditFor(sourceOf(d))).map((d) => d.key);

export function instrumentTable() {
  const all = playable();
  // As the app lists them: the retro instruments together under their own heading, last
  const group = (d) => (d.retro ? 'Retro (1990s soundfonts)' : d.category);
  const groups = CATEGORIES.filter((c) => all.some((d) => group(d) === c));
  const retro = all.filter((d) => d.retro).length;
  const lines = [
    `There are ${all.length} instruments in ${groups.length} groups. ${retro} of them are retro instruments (the 1990s General MIDI soundfonts and early sample sets), which the lists hide until you show them: see *Retro instruments* below.`,
    '',
    '| Group | Instruments |',
    '|---|---|',
    ...groups.map((c) => `| ${c} | ${all.filter((d) => group(d) === c).map((d) => d.name).join(', ')} |`),
    '',
    `- **Generated in the browser** (they work offline): ${all.filter((d) => !recorded(d) && !['custom', 'rack', 'multi'].includes(d.kind)).map((d) => d.name).join(', ')}.`,
    `- **Recorded** (${all.filter(recorded).length} instruments and kits, downloaded the first time you use them): all the others, except the Sampler, Drum Rack and Multi Sampler, which play your own sound files.`,
  ];
  return lines.join('\n');
}

export function creditsTable() {
  const rows = SAMPLE_CREDITS.map((c) => ({ c, names: playable().filter((d) => recorded(d) && creditFor(sourceOf(d)) === c).map((d) => d.name) })).filter((r) => r.names.length);
  return ['| Instruments | Samples | Licence |', '|---|---|---|', ...rows.map(({ c, names }) => `| ${names.join(', ')} | ${c.samples} | ${c.licence} |`)].join('\n');
}

/** The built-in plugins' credits: each family, how many plugins it gives, who made them. */
export function pluginCreditsTable() {
  const rows = [...PLUGIN_FAMILIES, ...GPL_PLUGIN_FAMILIES].map((f) => ({ f, c: PLUGIN_CREDITS.find((c) => c.family === f.family) }));
  return [
    '| Plugins | Made by | Licence |',
    '|---|---|---|',
    ...rows.map(({ f, c }) => {
      const inst = f.plugins.filter((p) => p.instrument).length;
      const fx = f.plugins.length - inst;
      const what = [fx && `${fx} effect${fx === 1 ? '' : 's'}`, inst && `${inst} instrument${inst === 1 ? '' : 's'}`].filter(Boolean).join(', ');
      return `| ${f.label}: ${what}${f.gpl ? ' (not in the one-file copy)' : ''} | ${c?.made ?? '?'} | ${c?.licence ?? f.licence} |`;
    }),
  ].join('\n');
}

/** Plugin families without a credit. */
const { GPL_PLUGIN_FAMILIES } = await import('../src/audio/plugins/pluginCatalogGpl.ts');
export const uncreditedPlugins = () => [...PLUGIN_FAMILIES, ...GPL_PLUGIN_FAMILIES].filter((f) => !PLUGIN_CREDITS.some((c) => c.family === f.family)).map((f) => f.family);

const between = (text, name, body) => {
  const start = `<!-- ${name}:start (generated by npm run guide-tables) -->`;
  const end = `<!-- ${name}:end -->`;
  const a = text.indexOf(start);
  const b = text.indexOf(end);
  if (a < 0 || b < a) throw new Error(`GUIDE.md has no ${name} markers`);
  return text.slice(0, a + start.length) + '\n' + body + '\n' + text.slice(b);
};

export function generatedGuide(text = readFileSync(GUIDE, 'utf8')) {
  return between(between(between(text, 'instruments', instrumentTable()), 'credits', creditsTable()), 'plugin-credits', pluginCreditsTable());
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const missing = uncredited();
  if (uncreditedPlugins().length) {
    console.error(`No credit in src/credits.ts for the plugin families: ${uncreditedPlugins().join(', ')}`);
    process.exit(1);
  }
  if (missing.length) {
    console.error(`No credit in src/credits.ts for the samples of: ${missing.join(', ')}`);
    process.exit(1);
  }
  writeFileSync(GUIDE, generatedGuide());
  console.log('GUIDE.md instrument list and credits updated');
}
