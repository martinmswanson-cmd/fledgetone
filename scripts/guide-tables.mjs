// The guide's instrument list and the Credits table, generated from the instrument catalog and
// src/credits.ts so they can't go stale. `npm run guide-tables` rewrites them in GUIDE.md;
// scripts/guideTables.test.mjs fails if they're out of date.
import { register } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

register(
  'data:text/javascript,' +
    encodeURIComponent(`export async function resolve(specifier, context, next) {
  try {
    return await next(specifier, context);
  } catch (err) {
    if (/^\\.\\.?\\//.test(specifier) && !/\\.[cm]?[jt]s$/.test(specifier)) return next(specifier + '.ts', context);
    throw err;
  }
}`)
);
const { INSTRUMENTS, CATEGORIES } = await import('../src/audio/instrumentCatalog.ts');
const { SAMPLE_CREDITS, creditFor } = await import('../src/credits.ts');

export const GUIDE = fileURLToPath(new URL('../GUIDE.md', import.meta.url));
const playable = () => Object.values(INSTRUMENTS).filter((d) => d.kind !== 'slicer' && d.kind !== 'audio' && d.kind !== 'bus' && d.kind !== 'plugin' && d.kind !== 'return');
const recorded = (d) => !!d.samples;

/** Instruments whose samples come from no listed source. */
export const uncredited = () => playable().filter((d) => recorded(d) && !creditFor(d.samples.baseUrl)).map((d) => d.key);

export function instrumentTable() {
  const all = playable();
  const groups = CATEGORIES.filter((c) => all.some((d) => d.category === c));
  const lines = [
    `There are ${all.length} instruments in ${groups.length} groups:`,
    '',
    '| Group | Instruments |',
    '|---|---|',
    ...groups.map((c) => `| ${c} | ${all.filter((d) => d.category === c).map((d) => d.name).join(', ')} |`),
    '',
    `- **Generated in the browser** (they work offline): ${all.filter((d) => !recorded(d) && !['custom', 'rack', 'multi'].includes(d.kind)).map((d) => d.name).join(', ')}.`,
    `- **Recorded** (${all.filter(recorded).length} instruments and kits, downloaded the first time you use them): all the others, except the Sampler, Drum Rack and Multi Sampler, which play your own sound files.`,
  ];
  return lines.join('\n');
}

export function creditsTable() {
  const rows = SAMPLE_CREDITS.map((c) => ({ c, names: playable().filter((d) => recorded(d) && creditFor(d.samples.baseUrl) === c).map((d) => d.name) })).filter((r) => r.names.length);
  return ['| Instruments | Samples | Licence |', '|---|---|---|', ...rows.map(({ c, names }) => `| ${names.join(', ')} | ${c.samples} | ${c.licence} |`)].join('\n');
}

const between = (text, name, body) => {
  const start = `<!-- ${name}:start (generated by npm run guide-tables) -->`;
  const end = `<!-- ${name}:end -->`;
  const a = text.indexOf(start);
  const b = text.indexOf(end);
  if (a < 0 || b < a) throw new Error(`GUIDE.md has no ${name} markers`);
  return text.slice(0, a + start.length) + '\n' + body + '\n' + text.slice(b);
};

export function generatedGuide(text = readFileSync(GUIDE, 'utf8')) {
  return between(between(text, 'instruments', instrumentTable()), 'credits', creditsTable());
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const missing = uncredited();
  if (missing.length) {
    console.error(`No credit in src/credits.ts for the samples of: ${missing.join(', ')}`);
    process.exit(1);
  }
  writeFileSync(GUIDE, generatedGuide());
  console.log('GUIDE.md instrument list and credits updated');
}
